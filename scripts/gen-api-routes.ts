/**
 * Generates app/api/v1/** route files from lib/server/endpoints.ts.
 * Run: npx tsx scripts/gen-api-routes.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { ENDPOINTS } from "../lib/server/endpoints";

const byFile = new Map<string, { method: string; handler: string }[]>();
for (const e of ENDPOINTS) {
  const segs = e.path
    .split("/")
    .filter(Boolean)
    .map((s) => s.replace(/^\{(\w+)\}$/, "[$1]"));
  const file = join("app/api/v1", ...segs, "route.ts");
  byFile.set(file, [...(byFile.get(file) ?? []), { method: e.method, handler: e.handler }]);
}
for (const [file, handlers] of byFile) {
  mkdirSync(dirname(file), { recursive: true });
  const exports = handlers.map((h) => `${h.handler} as ${h.method}`).join(", ");
  writeFileSync(file, `// Generated by scripts/gen-api-routes.ts — edit lib/server/endpoints.ts instead.\nexport { ${exports} } from "@/lib/server/routes";\n`);
}
console.log(`wrote ${byFile.size} route files for ${ENDPOINTS.length} endpoints`);
